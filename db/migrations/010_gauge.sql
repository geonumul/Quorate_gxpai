-- 010: 차압 설정 구간에 **차압계가 설치돼 있는가**
--
-- 조문: 고시 별표1 제4호 너목
--   "청정실 및 필요한 경우 아이솔레이터와 주변구역 사이에 **차압계가 설치되어야 한다.**
--    오염관리전략에서 차압에 대한 설정값 및 중요도를 고려하여야 한다.
--    중요하다고 확인된 차압은 **연속적으로 모니터하고 기록**하여야 한다."
--
-- 도면이 이미 구간별로 말해준다:
--   'Air Flow 10Pa' / 'Air Flow 15Pa'  = 차압이 **설정된** 구간
--   'Air Flow no차압'                  = 차압계 설치가 **요구되지 않는** 위치 (도면 범례 3번)
--   레이어 '차압계-아날로그'(21), '차압계-디지털'(7) = **설치된 차압계 위치**
--
-- has_gauge = true  : 이 구간 근처에 차압계가 있다
--             false : 없다  → 청정실 경계라면 PRES-005 위반
--             NULL  : 차압계 도면이 없는 시설 → 판정 불가(추측하지 않는다)
ALTER TABLE pressure_relation
    ADD COLUMN IF NOT EXISTS has_gauge   boolean,
    ADD COLUMN IF NOT EXISTS gauge_kind  text;     -- 아날로그 / 디지털
