-- 011: 방에 붙은 **인터락(연동장치)** 개수
--
-- 조문: 고시 별표1 제4호 파목
--   "이송해치 및 에어락(물품 및 작업원용)의 경우 입구용과 출구용 문이 **동시에 열려서는 안 된다**.
--    **A등급과 B등급 구역으로 연결되는 에어락의 경우 인터락 시스템을 사용해야 한다.**
--    C등급과 D등급 청정실로 연결되는 에어락의 경우, 최소한 시각경고시스템 및 필요한 경우
--    음성경고시스템 …"
--
--   ★등급별로 요구가 다르다. A/B 는 **인터락 필수**, C/D 는 시각경고면 된다.
--     구판(식약처 게시판)은 "인터락 또는 경보장치"로 뭉뚱그렸는데 현행(법제처)은 갈라놨다.
--     구판을 인용했으면 A/B 의 인터락 의무를 놓쳤을 것이다.
--
-- 도면: 레이어 `u-interlock` 의 **2점 선** 24개 = 에어락의 두 문을 잇는 연결선
--       ("이 둘은 동시에 열리면 안 된다"). 선의 중점이 그 에어락 방이다.
--
-- interlock_count = NULL : 인터락 도면이 없는 시설 → 판정 불가(추측하지 않는다)
--                   0    : 인터락 없음 → A/B 연결 에어락이면 ADJ-005 위반
ALTER TABLE room
    ADD COLUMN IF NOT EXISTS interlock_count integer;
