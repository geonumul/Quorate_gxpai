-- 012: 방별 **급기 풍량**(CMH)
--
-- ★단위가 도면에 적혀 있다: 천정기구배치도 레이어 `B-ZONE` 의 텍스트 **`풍량(CMH)`**.
--   TA 단위(CMH 인지 Pa 인지)는 오래 '보류'였는데, **도면 스스로 확정해 줬다**
--   (적어도 이 도면에서는. 기준 시설의 `TA` 레이어는 여전히 추정이다).
--
-- ⚠★그런데 **환기 횟수(ACH) 규칙은 만들지 않는다.**
--
--   수치(Class 100(A) 600회/hr · Class 10,000(B) 20회/hr)는
--   「GMP 조사평가 매뉴얼」이 인용한 **구 KGMP 해설서**에만 있다.
--   **현행 고시(별표1, 2023 개정 · PIC/S Annex 1 기반)에는 환기 횟수 수치가 없다.**
--   (별표1의 '환기' 언급 6건은 전부 EO 멸균 환기 등 **다른 맥락**이다 — 전수 확인)
--
--   현행은 오염관리전략(CCS)으로 타당성을 입증하게 한다.
--   수치를 박아 넣으면 **근거 없는 관행을 법인 것처럼** 판정하는 것이다. 하지 않는다.
--
--   → 풍량은 **데이터로만 적재**한다. 규칙이 켜지려면 두 가지가 더 필요하다:
--       ① 발주처 **자사 환기 기준** (몇 회/hr 로 관리하는가)
--       ② **천장고** (ACH = 풍량 ÷ (면적 × 천장고))
--     둘 다 오면 그날 규칙을 만든다. 발주처_확인요청서에 적어 뒀다.
ALTER TABLE room
    ADD COLUMN IF NOT EXISTS airflow_cmh double precision;
