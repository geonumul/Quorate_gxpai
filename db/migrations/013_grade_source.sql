-- 013: 등급이 **어디서 왔는지** 추적한다.
--
-- ★내가 크게 오해하고 있었다: "도면에 등급 표기가 0건 = 도면 결함 · 최대 병목".
--   **틀렸다.** 1차 미팅(2026-07-09) 대표님:
--
--     Q(geonumul) "그럼 이게 방별로 그레이드 등급이 매겨져 있는 거요?"
--     A(대표님)   "**방별로는 안 하고** … 아까 그 **구역** 말씀"
--     Q          "그럼 그런 건 따로 적혀 있지는 않은 거예요?"
--     A          "**그렇죠.** 이제 그건 **나중에**, 이 방을 1·2·3·4로 가든 a·b·c로 하든 쫙 해놓고
--                 '**a부터 b는 그레이드 B, d부터 f까지는 그레이드 C**' 이렇게 해주면
--                 [AI]가 알아서 그렇게 가게끔 해야죠."
--
--   → **등급이 도면에 없는 것은 정상이다.** 결함이 아니다.
--     등급은 사람이 **구역(zone)** 으로 묶어 지정하는 것이고, 엔진은 그걸 받아 채워야 한다.
--
--   그리고 **제형이 기본 등급을 정한다**(같은 미팅):
--     내용고형제(알약·캡슐) → D   ·   액제·연고·크림 → C   ·   주사제 → B 이상
--
-- grade_source
--   drawing          도면에 실제로 적혀 있었다 (참고도면: Grade 레이어 49건)
--   zone             프로파일의 grade_zones 에서 사람이 지정했다
--   product_default  제형 기본값 (미팅에서 확정)
--   NULL             모른다 → 등급 규칙이 판정하지 않는다
ALTER TABLE room
    ADD COLUMN IF NOT EXISTS grade_source text;
