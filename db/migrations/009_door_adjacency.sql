-- 009: 인접에 '문으로 이어졌는가'를 표시한다.
--
-- 왜 필요한가 — ADJ-001 이 **엉뚱한 것**을 보고 있었다.
--
--   지금까지 인접 = **벽을 맞댄 방**이었다. 그런데 조문이 말하는 건 그게 아니다.
--     고시 별표1 제4호 타목  : "작업원 **동선**은 D→C→B 로 점진적"
--     고시 별표17 제3.3호 라목: "청정도에 따른 타당한 순서로 **연결된** 구역에 배치"
--   둘 다 **사람, 물건이 오가는 길**을 말한다.
--   벽만 맞대고 문이 없으면 오갈 수 없다 → 등급이 급변해도 동선 위반이 아니다.
--
--   벽 맞댐으로 판정하면 **지나갈 수도 없는 두 방**을 '등급 급변'이라 우긴다(거짓 위반).
--
-- via_door = true  : 문으로 이어짐 (동선). ADJ-001 이 본다
-- via_door = false : 벽만 맞댐. 구획, 차압 검사가 본다
-- via_door IS NULL : 문 데이터가 없는 도면 → 판정 불가. 규칙이 벽 인접으로 폴백하되
--                    "문 정보 없음"을 근거에 남긴다
ALTER TABLE room_adjacency
    ADD COLUMN IF NOT EXISTS via_door boolean;
